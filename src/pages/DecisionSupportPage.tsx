import React, { useState, useEffect } from 'react';
import { 
  CheckCircle2, 
  Sliders, 
  FileText, 
  Sparkles, 
  Target, 
  Layers, 
  Info,
  RotateCcw
} from 'lucide-react';
import { DEMO_COUNTRIES, DEMO_VACCINES } from '../data/demoData';
import { apiService } from '../services/api';
import { DecisionSupportResult } from '../types';
import { DEFAULT_THRESHOLDS } from '../config/thresholds.config';
import { RiskBadge } from '../components/common/RiskBadge';
import { MetricCard } from '../components/common/MetricCard';

export const DecisionSupportPage: React.FC = () => {
  const [selectedCountry, setSelectedCountry] = useState<string>('IND');
  const [selectedVaccine, setSelectedVaccine] = useState<string>('MCV1');
  const [decisionResult, setDecisionResult] = useState<DecisionSupportResult | null>(null);

  const [thresholdHigh] = useState<number>(DEFAULT_THRESHOLDS.highRiskCoverage);
  const [thresholdTarget] = useState<number>(DEFAULT_THRESHOLDS.targetCoverage);
  const [simulatedBoost, setSimulatedBoost] = useState<number>(0);

  useEffect(() => {
    const fetchDecision = async () => {
      try {
        const res = await apiService.getDecisionSupport({
          country: selectedCountry,
          vaccine: selectedVaccine
        });
        setDecisionResult(res);
      } catch (err) {
        console.error(err);
      }
    };
    fetchDecision();
  }, [selectedCountry, selectedVaccine]);

  if (!decisionResult) return null;

  const simulatedCoverage = Math.min(100, Math.round((decisionResult.predictedCoverage + simulatedBoost) * 10) / 10);
  const effectiveChange = Math.round((simulatedCoverage - decisionResult.latestObservedCoverage) * 10) / 10;

  let dynamicRisk: 'HIGH' | 'MEDIUM' | 'LOW' | 'TARGET_ACHIEVED' = 'MEDIUM';
  if (simulatedCoverage < thresholdHigh || effectiveChange <= -3.0) {
    dynamicRisk = 'HIGH';
  } else if (simulatedCoverage >= thresholdTarget) {
    dynamicRisk = 'TARGET_ACHIEVED';
  } else {
    dynamicRisk = 'LOW';
  }

  return (
    <div className="space-y-6 animate-fadeIn">
      {/* Top Filter Console */}
      <div className="clean-card p-6 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-extrabold text-[#07362f]">
            Intelligent Decision Support &amp; Intervention Synthesis
          </h2>
          <p className="text-xs text-slate-500 font-medium mt-0.5">
            Rule-based public-health recommendations &amp; intervention simulation
          </p>
        </div>

        <div className="flex items-center gap-3">
          <div>
            <label className="text-[10px] uppercase font-bold text-slate-400 block mb-1">Country</label>
            <select
              value={selectedCountry}
              onChange={e => setSelectedCountry(e.target.value)}
              className="px-3 py-1.5 rounded-xl bg-white border border-[#d8ebe4] text-slate-800 text-xs font-semibold focus:outline-none focus:border-[#0d7a68] shadow-sm cursor-pointer"
            >
              {DEMO_COUNTRIES.map(c => (
                <option key={c.code} value={c.code}>{c.name} ({c.code})</option>
              ))}
            </select>
          </div>

          <div>
            <label className="text-[10px] uppercase font-bold text-slate-400 block mb-1">Vaccine</label>
            <select
              value={selectedVaccine}
              onChange={e => setSelectedVaccine(e.target.value)}
              className="px-3 py-1.5 rounded-xl bg-white border border-[#d8ebe4] text-slate-800 text-xs font-semibold focus:outline-none focus:border-[#0d7a68] shadow-sm cursor-pointer"
            >
              {DEMO_VACCINES.map(v => (
                <option key={v.code} value={v.code}>{v.code}</option>
              ))}
            </select>
          </div>
        </div>
      </div>

      {/* Academic Disclaimer Alert */}
      <div className="p-3.5 px-4 rounded-xl bg-[#e6f7f2] border-l-4 border-l-[#0d7a68] text-xs text-[#0a453b] flex items-start gap-3 shadow-sm">
        <Info className="w-4 h-4 text-[#0d7a68] shrink-0 mt-0.5" />
        <p className="leading-relaxed font-medium">
          <strong className="text-[#07362f]">Decision Support Disclaimer:</strong> The suggestions, risk classifications, and priority recommendations generated by this module represent rule-based decision-support simulations for academic research and programmatic planning.
        </p>
      </div>

      {/* Core Metrics Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <MetricCard
          title="LATEST OBSERVED"
          value={`${decisionResult.latestObservedCoverage}%`}
          subtitle="Baseline anchor year (2023)"
        />

        <MetricCard
          title="PROJECTED COVERAGE"
          value={`${simulatedCoverage}%`}
          subtitle={simulatedBoost > 0 ? `Includes +${simulatedBoost}% simulated boost` : 'TFT Model Projection'}
          badge={<RiskBadge level={dynamicRisk} size="sm" />}
        />

        <MetricCard
          title="PROJECTED CHANGE"
          value={`${effectiveChange > 0 ? `+${effectiveChange}` : effectiveChange}%`}
          unit="pts"
          subtitle="Net trajectory velocity"
          trend={{ value: `${effectiveChange}%`, positiveIsGood: true }}
        />

        <MetricCard
          title="OPERATIONAL PRIORITY"
          value={decisionResult.priorityLevel}
          subtitle="Rule classification output"
        />
      </div>

      {/* Synthesized Guidance Card */}
      <div className="clean-card p-6 space-y-5 border-l-4 border-l-[#0d7a68]">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-[#eaf4f0] pb-4">
          <div>
            <span className="text-[10px] font-mono font-bold uppercase tracking-wider text-[#0d7a68] px-2.5 py-0.5 rounded-full bg-[#ccfbf1] border border-[#99f6e4]">
              SYNTHESIZED ACTION GUIDANCE
            </span>
            <h3 className="text-lg font-bold text-[#07362f] mt-1.5">
              {decisionResult.suggestedAction}
            </h3>
          </div>

          <RiskBadge level={dynamicRisk} size="lg" />
        </div>

        {/* Decision Logic Rationale */}
        <div className="p-4 rounded-xl bg-[#f0faf7] border border-[#d8ebe4] space-y-2">
          <h4 className="text-xs font-bold uppercase tracking-wider text-slate-600 flex items-center gap-1.5">
            <FileText className="w-4 h-4 text-[#0d7a68]" />
            Decision Logic Rationale
          </h4>
          <p className="text-xs text-slate-700 leading-relaxed font-medium">
            {decisionResult.rationale}
          </p>
        </div>

        {/* Triggered Rules & Recommended Delivery Channels */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 pt-2">
          <div className="p-4 rounded-xl bg-white border border-[#e1efe9] space-y-2 shadow-sm">
            <span className="text-xs font-bold text-slate-500 uppercase tracking-wider block">
              Transparent Rules Triggered:
            </span>
            <div className="space-y-1.5">
              {decisionResult.triggeredRules.map((r, i) => (
                <div key={i} className="flex items-center gap-2 text-xs font-medium text-[#07362f]">
                  <CheckCircle2 className="w-3.5 h-3.5 text-[#0d7a68] shrink-0" />
                  <span>{r}</span>
                </div>
              ))}
            </div>
          </div>

          <div className="p-4 rounded-xl bg-white border border-[#e1efe9] space-y-2 shadow-sm">
            <span className="text-xs font-bold text-slate-500 uppercase tracking-wider block">
              Suggested Intervention Channels:
            </span>
            <div className="space-y-1.5">
              {decisionResult.recommendedChannels.map((c, i) => (
                <div key={i} className="flex items-center gap-2 text-xs text-slate-700 font-medium">
                  <span className="w-1.5 h-1.5 rounded-full bg-[#0d7a68] shrink-0" />
                  <span>{c}</span>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>

      {/* Simulator & Thresholds */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        <div className="clean-card p-6 space-y-4">
          <div className="flex items-center justify-between">
            <div className="space-y-0.5">
              <h3 className="text-sm font-bold text-[#07362f] flex items-center gap-2">
                <Sliders className="w-4 h-4 text-[#0d7a68]" />
                <span>Intervention Impact Simulator</span>
              </h3>
              <p className="text-xs text-slate-500">
                Simulate the effect of targeted campaign outreach on projected coverage
              </p>
            </div>
            {simulatedBoost > 0 && (
              <button
                onClick={() => setSimulatedBoost(0)}
                className="text-[11px] text-slate-500 hover:text-slate-800 flex items-center gap-1 font-semibold"
              >
                <RotateCcw className="w-3 h-3" />
                Reset
              </button>
            )}
          </div>

          <div className="p-4 rounded-xl bg-[#f0faf7] border border-[#d8ebe4] space-y-3">
            <div className="flex items-center justify-between text-xs">
              <span className="text-slate-700 font-semibold">Outreach Campaign Acceleration:</span>
              <span className="font-mono font-bold text-[#0d7a68]">+{simulatedBoost}% Coverage</span>
            </div>
            <input
              type="range"
              min="0"
              max="15"
              step="1"
              value={simulatedBoost}
              onChange={e => setSimulatedBoost(Number(e.target.value))}
              className="w-full accent-[#0d7a68] cursor-pointer"
            />
            <div className="flex justify-between text-[10px] text-slate-500 font-medium">
              <span>0% (Baseline)</span>
              <span>+5% (Mobile Teams)</span>
              <span>+10% (Mass SIA)</span>
              <span>+15% (Surge)</span>
            </div>
          </div>

          <p className="text-[11px] text-slate-500 font-medium">
            Projected outcome with simulated campaign: <strong className="text-[#07362f] font-mono font-bold">{simulatedCoverage}%</strong>.
          </p>
        </div>

        <div className="clean-card p-6 space-y-4">
          <div className="space-y-0.5">
            <h3 className="text-sm font-bold text-[#07362f] flex items-center gap-2">
              <Sliders className="w-4 h-4 text-[#14b8a6]" />
              <span>Configurable Threshold Parameters</span>
            </h3>
            <p className="text-xs text-slate-500">
              Defined in <code className="text-[#0d7a68] font-mono font-semibold">thresholds.config.ts</code>
            </p>
          </div>

          <div className="space-y-3">
            <div className="flex items-center justify-between p-3 rounded-xl bg-[#f0faf7] border border-[#d8ebe4] text-xs">
              <div>
                <span className="text-[#07362f] font-bold">High Risk Trigger Threshold</span>
                <p className="text-[10px] text-slate-500">Coverage below this triggers Emergency Intervention</p>
              </div>
              <span className="font-mono font-bold text-rose-600 px-2.5 py-1 rounded-full bg-rose-50 border border-rose-200">
                &lt; {thresholdHigh}%
              </span>
            </div>

            <div className="flex items-center justify-between p-3 rounded-xl bg-[#f0faf7] border border-[#d8ebe4] text-xs">
              <div>
                <span className="text-[#07362f] font-bold">WHO Target Coverage Benchmark</span>
                <p className="text-[10px] text-slate-500">Coverage at or above triggers Sustain mode</p>
              </div>
              <span className="font-mono font-bold text-[#0d7a68] px-2.5 py-1 rounded-full bg-[#ccfbf1] border border-[#99f6e4]">
                ≥ {thresholdTarget}%
              </span>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
